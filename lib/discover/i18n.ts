export const DISCOVER_MESSAGES: Record<
  DiscoverLanguage,
  Record<DiscoverKey, string>
> = { ar, en };

export function translate(
  language: DiscoverLanguage,
  key: DiscoverKey,
  params?: Record<string, string | number>
): string {
  let text: string = DISCOVER_MESSAGES[language][key];
  for (const [name, value] of Object.entries(params ?? {})) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

// A subject or an occasion the catalogue names that this build has no
// word for is shown as it is written, without its prefix.
export function label(language: DiscoverLanguage, key: string): string {
  const known = DISCOVER_MESSAGES[language] as Record<string, string>;
  return known[key] ?? known[`cat.${key}`] ?? key.replace(/^occ:/, "");
}

export const directionOf = (language: DiscoverLanguage) =>
  language === "ar" ? "rtl" : "ltr";

// 1.9K, 365.6K, 2.1M — the same digits in both languages.
export function compact(n: number): string {
  if (n < 1000) return String(n);
  if (n < 1_000_000) return `${(n / 1000).toFixed(n < 10_000 ? 1 : 0)}K`;
  return `${(n / 1_000_000).toFixed(1)}M`;
}
