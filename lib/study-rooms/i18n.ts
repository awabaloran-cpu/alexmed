export const ROOMS_MESSAGES: Record<RoomsLanguage, Record<RoomsKey, string>> = {
  ar,
  en,
};

export function translate(
  language: RoomsLanguage,
  key: RoomsKey,
  values?: Record<string, string | number>
): string {
  const template =
    ROOMS_MESSAGES[language][key] ?? ROOMS_MESSAGES.ar[key] ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match
  );
}

// A refusal from the server (its message is the reason key) as a sentence.
export function errorKey(message: string | undefined | null): RoomsKey {
  const key = `error.${message}` as RoomsKey;
  return key in ar ? key : "error.unknown";
}

